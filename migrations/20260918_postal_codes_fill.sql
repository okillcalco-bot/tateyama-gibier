-- 郵便番号マスタ（千葉県）と捕獲者台帳の郵便番号の補完 2026-09-18（追加のみ）
--
--   1) postal_codes … 日本郵便 KEN_ALL（utf_ken_all）の千葉県分 3603件（posuto 2026.9.0 同梱データより）。
--      neighborhood='' の行は「以下に掲載がない場合」（市の代表番号）。
--   2) hunters.postal_code が空の人について、住所（先頭の「千葉県」と空白を除く）に
--      市名＋大字名が最も長く一致する行の郵便番号を入れる。大字が見つからない場合は市の代表番号。
--      既に入っている郵便番号は触らない。住所が無い人はそのまま（宛名ラベルで「住所未登録」と出る）。
--   3) 最後の select が「まだ入っていない人」。県外・表記ゆれはここに残るので手で入れる。

create table if not exists postal_codes (
  code         text not null,          -- 7桁（ハイフン無し）
  prefecture   text not null,
  city         text not null,
  neighborhood text not null default '', -- 大字・町名（'' = 以下に掲載がない場合）
  primary key (code, city, neighborhood)
);
create index if not exists idx_postal_codes_city on postal_codes(city);
comment on table postal_codes is '郵便番号マスタ（千葉県のみ・KEN_ALL）。捕獲者台帳の宛名ラベル用';

