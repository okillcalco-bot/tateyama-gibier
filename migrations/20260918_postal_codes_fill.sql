-- ── 捕獲者台帳へ補完 ──
with h as (
  select id, regexp_replace(regexp_replace(address, '^千葉県', ''), '[\s　]', '', 'g') as a
  from hunters where deleted_at is null and address is not null and address <> '' and (postal_code is null or postal_code = '')
), m as (
  select h.id, p.code, length(p.city || p.neighborhood) as l
  from h join postal_codes p on h.a like p.city || p.neighborhood || '%'
), best as (
  select distinct on (id) id, code from m order by id, l desc, code
)
update hunters set postal_code = substr(best.code,1,3) || '-' || substr(best.code,4), updated_at = now()
from best where hunters.id = best.id;

