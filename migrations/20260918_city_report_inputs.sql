--   収支は会計事務所から翌月に届くため、報告月の分が無いときは Excel 生成時に直近の月を使う（見出しもその月にする）。

create table if not exists public.city_report_inputs (
  month       text not null,
  kind        text not null,
  data        jsonb not null default '{}'::jsonb,
  source      text,
  updated_by  text,
  updated_at  timestamptz not null default now(),
  primary key (month, kind)
);
alter table public.city_report_inputs enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename = 'city_report_inputs' and policyname = 'allow_all') then
    create policy allow_all on public.city_report_inputs for all using (true) with check (true);
  end if;
end $$;
grant select, insert, update, delete on public.city_report_inputs to anon, authenticated;

