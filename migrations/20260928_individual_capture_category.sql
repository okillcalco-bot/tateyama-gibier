-- 個体の「捕獲区分」を追加（追加のみ）
--
-- きっかけ（2026-09-28）
--   アライグマは有害鳥獣駆除の個体を登録して市役所へ報告しているが、駆除ではなく個人宅で
--   捕獲された個体を食用として受け入れ・出荷したい。同じ individuals に入れると
--   市役所へ出す捕獲票・様式に駆除の頭数として混ざってしまう。
--
-- 決めたこと
--   capture_category: NULL（または '駆除'）= これまでどおりの駆除個体（市役所報告の対象）
--                     '駆除外'              = 個人宅など駆除以外で捕獲した個体（市役所報告の対象外）
--   個体管理番号は駆除の番号列（市役所の紙台帳と一致させている TGC-08-ア001〜）とは別に
--   TGC-08-アコ001〜（コ=個人）を使う。採番トリガは '^TGC-08-ア[0-9]+$' だけを数えるため、
--   アコ の番号は駆除の番号列に影響しない。
alter table public.individuals add column if not exists capture_category text;

comment on column public.individuals.capture_category is
  '捕獲区分。NULL/駆除=有害鳥獣駆除（市役所報告の対象）、駆除外=個人宅など駆除以外の捕獲（市役所報告の対象外）';
